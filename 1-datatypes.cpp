// DATA-TYPES in CPP

#include <iostream>
using namespace std;
int main()
{
    // INTEGER DATA TYPES

    int age = 20;                   // integer data type
    short int shortAge = 20;        // int data type but shorter in size than int
    long int longAge = 20;          // int data type but longer in size than int
    long long int longLongAge = 20; // int data type but longer in size than long int
    // signed int
    int temperature = -10; // signed int --> stores both positive and negative values
    // unsigned int
    unsigned int positiveTemperature = 10; // unsigned int --> stores only positive values

    float height = 5.9; // float data type
    double weight = 70.5; // double data type

    char grade = 'A'; // character data type

    bool isStudent = true; // boolean data type

    string name = "Zeeshan"; // string data type
}
